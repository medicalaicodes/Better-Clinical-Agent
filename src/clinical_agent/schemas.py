"""
Data Schemas for Multimodal Clinical Agent Reasoning
Defines evidence packets, agent claims, disagreement logs, and clinical reports.
"""

from enum import Enum
from typing import List, Dict, Optional, Any
from dataclasses import dataclass, field


class ModalityType(str, Enum):
    CXR = "chest_xray"
    CT = "ct_scan"
    MRI = "mri_brain"
    EHR = "structured_ehr"
    NOTES = "clinical_notes"
    GENOMICS = "genomics_omics"


@dataclass
class EvidencePacket:
    """Structured evidence output from a modality reader or specialist tool."""
    modality: ModalityType
    findings: List[str]
    confidence: float  # 0.0 to 1.0
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class AgentClaim:
    """A claim generated by a specialist agent grounded in evidence."""
    agent_id: str
    modality: ModalityType
    claim_text: str
    supporting_evidence: List[EvidencePacket]
    uncertainty_score: float  # Epistemic uncertainty (0.0 = high certainty, 1.0 = highly uncertain)


@dataclass
class ConflictLog:
    """Captures cross-modal disagreements rather than overwriting or forcing consensus."""
    modality_a: ModalityType
    claim_a: str
    modality_b: ModalityType
    claim_b: str
    description: str


@dataclass
class ClinicalReport:
    """Final aggregated diagnostic report with provenance and conflict disclosures."""
    primary_impression: str
    differential_diagnoses: List[str]
    claims: List[AgentClaim]
    conflicts: List[ConflictLog]
    missing_modalities: List[ModalityType]
    overall_confidence: float
